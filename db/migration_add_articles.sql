-- PostgreSQL tự chuyển tên bảng/cột không có dấu nháy về chữ thường.
--
-- Mô hình giống `tools` + `categories`, nhưng mỗi bài viết bắt buộc có
-- `original_url` (link truy cập bài viết gốc) và có thể kèm nội dung
-- (`content` markdown/HTML nhập tay hoặc `content_url` trỏ tới markdown raw).
-- =============================================================================

CREATE TABLE IF NOT EXISTS article_categories (
  category_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR(100) NOT NULL UNIQUE,
  description   TEXT
);

CREATE TABLE IF NOT EXISTS articles (
  article_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title           VARCHAR(255) NOT NULL,
  slug            VARCHAR(255) NOT NULL UNIQUE,
  category_id     BIGINT REFERENCES article_categories(category_id) ON DELETE SET NULL,
  summary         TEXT,
  thumbnail_url   VARCHAR(1000),
  content         TEXT,
  content_url     VARCHAR(1000),
  original_url    VARCHAR(1000) NOT NULL,
  original_source VARCHAR(150),
  published_at    DATE,
  is_published    BOOLEAN NOT NULL DEFAULT TRUE,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT articles_original_url_check CHECK (original_url ~* '^https?://'),
  CONSTRAINT articles_content_url_check  CHECK (content_url  IS NULL OR content_url  ~* '^https?://'),
  CONSTRAINT articles_thumbnail_url_check CHECK (thumbnail_url IS NULL OR thumbnail_url ~* '^https?://')
);

CREATE INDEX IF NOT EXISTS idx_articles_category_id ON articles(category_id);
CREATE INDEX IF NOT EXISTS idx_articles_published   ON articles(is_published, published_at DESC);

-- Dùng chung hàm trigger của schema_v2; CREATE OR REPLACE giúp migration chạy độc lập.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_articles_updated_at ON articles;
CREATE TRIGGER trg_articles_updated_at
  BEFORE UPDATE ON articles
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- API Vercel hiện dùng SUPABASE_ANON_KEY: chỉ công khai quyền đọc bài đã publish.
ALTER TABLE article_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE articles           ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO anon;
GRANT SELECT ON article_categories, articles TO anon;

DROP POLICY IF EXISTS "Public can read article categories" ON article_categories;
DROP POLICY IF EXISTS "Public can read published articles" ON articles;

CREATE POLICY "Public can read article categories" ON article_categories FOR SELECT TO anon USING (true);
CREATE POLICY "Public can read published articles" ON articles           FOR SELECT TO anon USING (is_published = true);
